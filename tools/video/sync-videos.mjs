// Regenerate src/data/videos.js from whatever is in public/videos/ (stem mNN-<moduleId>.mp4).
// usage: node tools/video/sync-videos.mjs
import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, 'public', 'videos')

const rows = readdirSync(dir)
  .filter((f) => /^m\d\d-.+\.mp4$/.test(f))
  .sort()
  .map((f) => {
    const stem = f.replace(/\.mp4$/, '')
    for (const ext of ['vtt', 'jpg']) {
      if (!existsSync(join(dir, `${stem}.${ext}`))) throw new Error(`missing ${stem}.${ext}`)
    }
    const secs = Math.floor(+execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', join(dir, f)]).toString())
    const length = `${Math.floor(secs / 60)}:${String(secs % 60).padStart(2, '0')}`
    return `  ${stem.replace(/^m\d\d-/, '')}: { file: '${stem}', length: '${length}' },`
  })

writeFileSync(join(root, 'src', 'data', 'videos.js'), `/**
 * Module intro videos (built by tools/video — see tools/video/README.md).
 * Generated by tools/video/sync-videos.mjs: moduleId -> file stem in public/videos/ and running time.
 */
const videos = {
${rows.join('\n')}
}

export function moduleVideo(moduleId) {
  const v = videos[moduleId]
  if (!v) return null
  const base = \`\${import.meta.env.BASE_URL}videos/\${v.file}\`
  return { ...v, mp4: \`\${base}.mp4\`, vtt: \`\${base}.vtt\`, poster: \`\${base}.jpg\` }
}
`)
