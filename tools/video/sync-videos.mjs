// Regenerate src/data/videos.js from whatever is in public/videos/:
//   mNN-<moduleId>.mp4              module intro
//   mNN-<moduleId>--<lessonId>.mp4  lesson video
// usage: node tools/video/sync-videos.mjs
import { execFileSync } from 'node:child_process'
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const dir = join(root, 'public', 'videos')

const all = readdirSync(dir)
  .filter((f) => /^m\d\d-.+\.mp4$/.test(f))
  .sort()
  .map((f) => {
    const stem = f.replace(/\.mp4$/, '')
    for (const ext of ['vtt', 'jpg']) {
      if (!existsSync(join(dir, `${stem}.${ext}`))) throw new Error(`missing ${stem}.${ext}`)
    }
    const secs = Math.floor(+execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', join(dir, f)]).toString())
    const length = `${Math.floor(secs / 60)}:${String(secs % 60).padStart(2, '0')}`
    const [mod, lesson] = stem.replace(/^m\d\d-/, '').split('--')
    return { key: lesson ? `${mod}/${lesson}` : mod, lesson: !!lesson, row: `  '${lesson ? `${mod}/${lesson}` : mod}': { file: '${stem}', length: '${length}' },` }
  })
const rows = all.filter((r) => !r.lesson).map((r) => r.row)
const lessonRows = all.filter((r) => r.lesson).map((r) => r.row)

writeFileSync(join(root, 'src', 'data', 'videos.js'), `/**
 * Intro videos for modules and lessons (built by tools/video — see tools/video/README.md).
 * Generated by tools/video/sync-videos.mjs — do not edit by hand.
 */
const modules = {
${rows.join('\n')}
}

/** 'moduleId/lessonId' -> lesson video */
const lessons = {
${lessonRows.join('\n')}
}

function withUrls(v) {
  if (!v) return null
  const base = \`\${import.meta.env.BASE_URL}videos/\${v.file}\`
  return { ...v, mp4: \`\${base}.mp4\`, vtt: \`\${base}.vtt\`, poster: \`\${base}.jpg\` }
}

export const moduleVideo = (moduleId) => withUrls(modules[moduleId])
export const lessonVideo = (moduleId, lessonId) => withUrls(lessons[\`\${moduleId}/\${lessonId}\`])
`)
console.log(`${rows.length} module videos, ${lessonRows.length} lesson videos`)
